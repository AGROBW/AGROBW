create or replace function public.render_whatsapp_gateway_template(
  p_template text,
  p_payload jsonb
)
returns text
language plpgsql
immutable
security invoker
set search_path = pg_catalog, pg_temp
as $$
declare
  v_result text := p_template;
  v_key text;
  v_value text;
begin
  if jsonb_typeof(coalesce(p_payload, '{}'::jsonb)) <> 'object' then
    raise exception 'Payload de template invalido' using errcode = '22023';
  end if;

  for v_key, v_value in
    select key, value from jsonb_each_text(coalesce(p_payload, '{}'::jsonb))
  loop
    if v_key ~ '^[a-z][a-z0-9_]{0,49}$' then
      v_result := replace(v_result, '{{' || v_key || '}}', left(coalesce(v_value, ''), 300));
    end if;
  end loop;

  v_result := regexp_replace(v_result, '\{\{[a-z][a-z0-9_]{0,49}\}\}', '', 'g');
  return left(trim(v_result), 1800);
end;
$$;

create or replace function public.enqueue_whatsapp_gateway_event(
  p_event_type text,
  p_event_key text,
  p_source_table text,
  p_source_id uuid,
  p_payload jsonb default '{}'::jsonb,
  p_link_path text default null,
  p_recipient_kind text default 'admin_default',
  p_recipient_user_id uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_template public.whatsapp_gateway_templates%rowtype;
  v_job_id uuid;
  v_message text;
begin
  if p_event_type like 'marketing_%' then
    raise exception 'Eventos de marketing WhatsApp exigem consentimento especifico'
      using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.whatsapp_gateway_settings settings
    where settings.id = '00000000-0000-0000-0000-000000000020'
      and settings.is_enabled
      and settings.base_url is not null
      and nullif(trim(settings.auth_secret), '') is not null
      and (
        (p_recipient_kind = 'admin_default' and settings.default_recipient_phone is not null)
        or p_recipient_kind = 'user'
      )
  ) then
    return null;
  end if;

  select * into v_template
  from public.whatsapp_gateway_templates templates
  where templates.event_type = p_event_type
    and templates.is_enabled;

  if not found then
    return null;
  end if;
  if p_event_key is null or char_length(trim(p_event_key)) not between 3 and 300 then
    raise exception 'Chave de evento invalida' using errcode = '22023';
  end if;
  if p_source_table is null or p_source_table !~ '^[a-z][a-z0-9_]{2,79}$' then
    raise exception 'Tabela de origem invalida' using errcode = '22023';
  end if;
  if p_link_path is not null and p_link_path !~ '^/(admin|minha-conta)/[A-Za-z0-9/_-]*$' then
    raise exception 'Link administrativo invalido' using errcode = '22023';
  end if;
  if p_recipient_kind not in ('admin_default', 'user') then
    raise exception 'Tipo de destinatario invalido' using errcode = '22023';
  end if;
  if p_recipient_kind = 'user' and p_recipient_user_id is null then
    raise exception 'Usuario destinatario obrigatorio' using errcode = '22023';
  end if;
  if jsonb_typeof(coalesce(p_payload, '{}'::jsonb)) <> 'object'
    or octet_length(coalesce(p_payload, '{}'::jsonb)::text) > 4096 then
    raise exception 'Payload de evento invalido' using errcode = '22023';
  end if;

  v_message := public.render_whatsapp_gateway_template(v_template.body_template, p_payload);
  if nullif(trim(v_message), '') is null then
    raise exception 'Template resultou em mensagem vazia' using errcode = '22023';
  end if;

  insert into public.whatsapp_gateway_jobs (
    idempotency_key,
    event_type,
    event_key,
    event_cycle,
    source_table,
    source_id,
    recipient_kind,
    recipient_user_id,
    message_body,
    link_path,
    metadata
  ) values (
    gen_random_uuid(),
    p_event_type,
    trim(p_event_key),
    case
      when p_event_type = 'admin_announcement_pending'
        then nullif(p_payload->>'moderation_cycle', '')::bigint
      else null
    end,
    p_source_table,
    p_source_id,
    p_recipient_kind,
    p_recipient_user_id,
    v_message,
    p_link_path,
    coalesce(p_payload, '{}'::jsonb)
  )
  on conflict (event_type, event_key) do nothing
  returning id into v_job_id;

  return v_job_id;
end;
$$;

create or replace function public.try_enqueue_whatsapp_gateway_event(
  p_event_type text,
  p_event_key text,
  p_source_table text,
  p_source_id uuid,
  p_payload jsonb default '{}'::jsonb,
  p_link_path text default null,
  p_recipient_kind text default 'admin_default',
  p_recipient_user_id uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_error_code text;
begin
  return public.enqueue_whatsapp_gateway_event(
    p_event_type,
    p_event_key,
    p_source_table,
    p_source_id,
    p_payload,
    p_link_path,
