create or replace function public.queue_whatsapp_admin_support_event()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_ticket public.support_tickets%rowtype;
  v_sender_user_id uuid;
  v_recent_jobs integer;
  v_limit_error_code text;
  v_limit_lock_acquired boolean := false;
  v_limit_lock_attempt integer;
begin
  if new.sender_type <> 'user' then
    return new;
  end if;
  select * into v_ticket from public.support_tickets tickets where tickets.id = new.ticket_id;
  if not found or v_ticket.status not in ('open', 'in_progress', 'waiting_user') then
    return new;
  end if;
  v_sender_user_id := coalesce(new.sender_user_id, v_ticket.user_id);
  begin
    for v_limit_lock_attempt in 1..20 loop
      v_limit_lock_acquired := pg_try_advisory_xact_lock(
        hashtextextended(v_sender_user_id::text, 8675309)
      );
      exit when v_limit_lock_acquired;
      perform pg_sleep(0.01);
    end loop;
    if not v_limit_lock_acquired then
      begin
        insert into public.whatsapp_gateway_enqueue_failures (
          event_type, source_table, source_id, error_code
        ) values (
          'admin_support_rate_limit', 'support_ticket_messages', new.id, 'SUPPORT_RATE_LIMIT_BUSY'
        );
      exception when others then
        null;
      end;
      raise warning 'Limite WhatsApp do suporte ocupado para a mensagem %', new.id;
      return new;
    end if;
    select count(*) into v_recent_jobs
    from public.whatsapp_gateway_jobs jobs
    join public.support_ticket_messages messages on messages.id = jobs.source_id
    where jobs.event_type = 'admin_support_message'
      and messages.sender_user_id = v_sender_user_id
      and jobs.created_at >= now() - interval '10 minutes';
    if v_recent_jobs >= 5 then
      return new;
    end if;
  exception when others then
    v_limit_error_code := sqlstate;
    begin
      insert into public.whatsapp_gateway_enqueue_failures (
        event_type, source_table, source_id, error_code
      ) values (
        'admin_support_rate_limit', 'support_ticket_messages', new.id, left(v_limit_error_code, 80)
      );
    exception when others then
      null;
    end;
    raise warning 'Falha isolada no limite WhatsApp do suporte %: %', new.id, v_limit_error_code;
    return new;
  end;
  perform public.try_enqueue_whatsapp_gateway_event(
    'admin_support_message', new.ticket_id::text || ':' || floor(extract(epoch from now()) / 600)::bigint::text,
    'support_ticket_messages', new.id,
    jsonb_build_object(
      'subject', left(coalesce(nullif(trim(v_ticket.subject), ''), 'Suporte'), 300),
      'sender', left(coalesce(nullif(trim(new.sender_name), ''), 'Usuario'), 120),
      'priority', upper(coalesce(v_ticket.priority, 'medium'))
    ), '/admin/support'
  );
  return new;
end;
$$;

