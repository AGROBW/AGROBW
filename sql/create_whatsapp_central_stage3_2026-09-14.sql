create or replace function public.update_whatsapp_gateway_template_admin_safe(
  p_event_type text,
  p_body_template text,
  p_is_enabled boolean
)
returns table (
  event_type text,
  label text,
  body_template text,
  allowed_placeholders text[],
  is_enabled boolean,
  updated_at timestamptz
)
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_allowed text[];
  v_unknown text[];
  v_probe_payload jsonb;
  v_without_valid_placeholders text;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Unauthorized' using errcode = '42501';
  end if;
  if nullif(trim(coalesce(p_body_template, '')), '') is null
    or char_length(trim(p_body_template)) > 1600 then
    raise exception 'Template invalido' using errcode = '22023';
  end if;
  if p_event_type = 'marketing_announcement_campaign' and coalesce(p_is_enabled, false) then
    raise exception 'Campanhas de WhatsApp exigem opt-in especifico antes da ativacao' using errcode = '42501';
  end if;

  select templates.allowed_placeholders into v_allowed
  from public.whatsapp_gateway_templates templates
  where templates.event_type = p_event_type;
  if not found then
    raise exception 'Tipo de evento desconhecido' using errcode = '22023';
  end if;

  select array_agg(distinct matches.placeholder_match[1]) into v_unknown
  from regexp_matches(
    p_body_template,
    '\{\{([a-z][a-z0-9_]{0,49})\}\}',
    'g'
  ) as matches(placeholder_match)
  where not (matches.placeholder_match[1] = any(v_allowed));
  if cardinality(coalesce(v_unknown, array[]::text[])) > 0 then
    raise exception 'Placeholder nao permitido: %', array_to_string(v_unknown, ', ')
      using errcode = '22023';
  end if;

  v_without_valid_placeholders := regexp_replace(
    p_body_template,
    '\{\{[a-z][a-z0-9_]{0,49}\}\}',
    '',
    'g'
  );
  if position('{{' in v_without_valid_placeholders) > 0
    or position('}}' in v_without_valid_placeholders) > 0 then
    raise exception 'Sintaxe de placeholder invalida' using errcode = '22023';
  end if;

  select coalesce(jsonb_object_agg(keys.placeholder, 'exemplo'), '{}'::jsonb)
  into v_probe_payload
  from unnest(v_allowed) as keys(placeholder);
  if nullif(trim(public.render_whatsapp_gateway_template(p_body_template, v_probe_payload)), '') is null then
    raise exception 'Template resultaria em mensagem vazia' using errcode = '22023';
  end if;

  update public.whatsapp_gateway_templates templates
  set
    body_template = trim(p_body_template),
    is_enabled = coalesce(p_is_enabled, templates.is_enabled),
    last_updated_by = auth.uid()
  where templates.event_type = p_event_type;

  if not found then
    raise exception 'Tipo de evento desconhecido' using errcode = '22023';
  end if;

  return query
  select templates.event_type, templates.label, templates.body_template,
    templates.allowed_placeholders,
    templates.is_enabled, templates.updated_at
  from public.whatsapp_gateway_templates templates
  where templates.event_type = p_event_type;
end;
$$;

drop function if exists public.get_whatsapp_gateway_queue_summary_admin_safe();
create or replace function public.get_whatsapp_gateway_queue_summary_admin_safe()
returns table (
  pending_count bigint,
  processing_count bigint,
  retry_count bigint,
  sent_today_count bigint,
  dead_letter_count bigint,
  enqueue_failure_count bigint,
  last_queued_at timestamptz,
  last_sent_at timestamptz
)
language plpgsql
