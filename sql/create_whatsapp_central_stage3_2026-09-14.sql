    null;
  end;
  raise warning 'Falha isolada ao enfileirar evento WhatsApp %: %', p_event_type, v_error_code;
  return null;
end;
$$;

create or replace function public.claim_whatsapp_gateway_jobs(
  p_limit integer,
  p_worker_id uuid
)
returns setof public.whatsapp_gateway_jobs
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Unauthorized' using errcode = '42501';
  end if;
  if p_worker_id is null then
    raise exception 'Worker obrigatorio' using errcode = '22023';
  end if;

  update public.whatsapp_gateway_jobs jobs
  set
    status = 'dead_letter',
    last_error_code = 'LEASE_EXPIRED',
    locked_at = null,
    locked_by = null
  where jobs.status = 'processing'
    and jobs.locked_at < now() - interval '10 minutes'
    and jobs.attempts >= jobs.max_attempts;

  update public.whatsapp_gateway_jobs jobs
  set
    status = 'skipped',
    last_error_code = 'ADMIN_EVENT_EXPIRED',
    locked_at = null,
    locked_by = null
  where jobs.event_type like 'admin_%'
    and (
      jobs.status in ('pending', 'retry')
      or (jobs.status = 'processing' and jobs.locked_at < now() - interval '10 minutes')
    )
    and jobs.created_at < now() - interval '24 hours';

  return query
  with candidates as (
    select jobs.id
    from public.whatsapp_gateway_jobs jobs
    where (
      (jobs.status in ('pending', 'retry') and jobs.available_at <= now())
      or (jobs.status = 'processing' and jobs.locked_at < now() - interval '10 minutes')
    )
      and jobs.attempts < jobs.max_attempts
    order by jobs.available_at, jobs.created_at
    for update skip locked
    limit least(greatest(coalesce(p_limit, 25), 1), 100)
  )
  update public.whatsapp_gateway_jobs jobs
  set
    status = 'processing',
    attempts = jobs.attempts + 1,
    locked_at = now(),
    locked_by = p_worker_id,
    last_attempt_at = now(),
    last_error_code = null
  from candidates
  where jobs.id = candidates.id
  returning jobs.*;
end;
$$;

create or replace function public.release_whatsapp_gateway_jobs(
  p_worker_id uuid,
  p_job_ids uuid[]
)
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_released integer;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Unauthorized' using errcode = '42501';
  end if;
  if p_worker_id is null or coalesce(cardinality(p_job_ids), 0) = 0 then
    return 0;
  end if;

  update public.whatsapp_gateway_jobs jobs
  set
    status = case when jobs.attempts <= 1 then 'pending' else 'retry' end,
    attempts = greatest(jobs.attempts - 1, 0),
    available_at = now(),
    locked_at = null,
    locked_by = null,
    last_attempt_at = null
  where jobs.id = any(p_job_ids)
    and jobs.status = 'processing'
    and jobs.locked_by = p_worker_id;

  get diagnostics v_released = row_count;
  return v_released;
end;
$$;

