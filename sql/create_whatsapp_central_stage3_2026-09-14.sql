create or replace function public.fail_whatsapp_gateway_job(
  p_job_id uuid,
  p_worker_id uuid,
  p_error_code text,
  p_http_status integer default null,
  p_retryable boolean default true
)
returns text
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_job public.whatsapp_gateway_jobs%rowtype;
  v_next_status text;
  v_delay_seconds integer;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Unauthorized' using errcode = '42501';
  end if;

  select * into v_job
  from public.whatsapp_gateway_jobs jobs
  where jobs.id = p_job_id
    and jobs.status = 'processing'
    and jobs.locked_by = p_worker_id
  for update;

  if not found then
    return null;
  end if;

  v_next_status := case
    when coalesce(p_retryable, true) and v_job.attempts < v_job.max_attempts then 'retry'
    else 'dead_letter'
  end;
  v_delay_seconds := least(
    3600,
    (30 * power(2, greatest(v_job.attempts - 1, 0)))::integer
  );

  update public.whatsapp_gateway_jobs jobs
  set
    status = v_next_status,
    available_at = case when v_next_status = 'retry'
      then now() + make_interval(secs => v_delay_seconds)
      else jobs.available_at
    end,
    last_http_status = p_http_status,
    last_error_code = left(coalesce(nullif(trim(p_error_code), ''), 'UNKNOWN_ERROR'), 160),
    locked_at = null,
    locked_by = null
  where jobs.id = v_job.id;

  return v_next_status;
end;
